/**
 * Real-GaussDB introspection-inference journeys (S3-1): a hand-written
 * all-column table (phase-1 scalar set + the six Oracle-compat types + an
 * enum column + array columns + every default shape) flows through
 * introspect → inferPslContract → printPsl, and the inferred PSL is then
 * planned, applied to a fresh database, and introspect-verified — proving the
 * inferred contract is executable, not just text.
 *
 * The A-mode `date` type is deliberately absent from the table: it lands in
 * the catalog under its private `datea` type name and infers to
 * `Unsupported("datea")` (documented steer-to-Timestamp boundary), which has
 * no executable DDL form to round-trip. Journey 1 adds it back live to pin
 * that Unsupported spelling.
 *
 * Isolated in a throwaway database (`prisma_8_infer_journeys_gaussdb`)
 * dropped and recreated on a maintenance connection; skips when `GAUSSDB_URL`
 * is not set.
 */

import gaussdbAdapterDescriptor from '@internal/adapter-gaussdb/control';
import postgresDriverDescriptor from '@internal/driver-postgres/control';
import sqlFamilyDescriptor from '@internal/family-sql/control';
import { createControlStack } from '@internal/framework-components/control';
import { printPsl } from '@internal/psl-printer';
import gaussdbTargetDescriptor from '@internal/target-gaussdb/control';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import {
  applyPlan,
  buildContractFromPsl,
  createGaussDbDriver,
  emptySchema,
  familyInstance,
  frameworkComponents,
  GaussDbControlDriver,
  planContract,
  timeouts,
} from '../_harness/gaussdb-migrations';

const MAINTENANCE_URL = process.env['GAUSSDB_URL'] ?? '';
const INFER_TEST_DB = 'prisma_8_infer_journeys_gaussdb';
const TABLE = 'gj_infer_probe';
const ENUM_TYPE = 'gj_infer_status';

function inferTestDatabaseUrl(): string {
  const url = new URL(MAINTENANCE_URL);
  url.pathname = `/${INFER_TEST_DB}`;
  return url.toString();
}

const probeStack = createControlStack({
  family: sqlFamilyDescriptor,
  target: gaussdbTargetDescriptor,
  adapter: gaussdbAdapterDescriptor,
  driver: {
    ...postgresDriverDescriptor,
    targetId: 'gaussdb' as const,
    id: 'gaussdb' as const,
    async create(url: string) {
      return new GaussDbControlDriver(await postgresDriverDescriptor.create(url));
    },
  },
  extensions: [],
});

// Types with an executable round-trip only: `date` is excluded (private
// `datea` type, Unsupported by the documented steer-to-Timestamp decision),
// and `c_numeric` carries no literal default — a numeric literal default
// fails DDL rendering on the plan path for AUTHORED contracts too
// (gaussdb/numeric@1 decodeJson requires decimal text; pre-existing, logged
// in verification-results.md section ten).
const ALL_COLUMN_DDL = `CREATE TABLE ${TABLE} (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  c_int          int4 DEFAULT 42,
  c_bigint       int8 DEFAULT 7,
  c_smallint     int2,
  c_float8       float8 DEFAULT 1.5,
  c_real         real,
  c_bool         boolean DEFAULT true,
  c_text         text DEFAULT 'hello',
  c_varchar      varchar(50),
  c_char         char(10),
  c_numeric      numeric(12,2),
  c_jsonb        jsonb DEFAULT '{}',
  c_json         json,
  c_bytes        bytea,
  c_uuid         uuid,
  c_timestamptz  timestamptz DEFAULT now(),
  c_timestamp    timestamp,
  c_time         time,
  c_timetz       timetz,
  c_inet         inet,
  c_enum         ${ENUM_TYPE} DEFAULT 'new',
  c_text_arr     text[] DEFAULT '{}',
  c_int_arr      int4[],
  c_number       number(10,2),
  c_number_bare  number,
  c_varchar2     varchar2(30),
  c_nvarchar2    nvarchar2(30),
  c_clob         clob,
  c_blob         blob,
  c_raw          raw(32)
)`;

const PHYSICAL_COLUMN_NAMES = [
  'c_int',
  'c_bigint',
  'c_smallint',
  'c_float8',
  'c_real',
  'c_bool',
  'c_text',
  'c_varchar',
  'c_char',
  'c_numeric',
  'c_jsonb',
  'c_json',
  'c_bytes',
  'c_uuid',
  'c_timestamptz',
  'c_timestamp',
  'c_time',
  'c_timetz',
  'c_inet',
  'c_enum',
  'c_text_arr',
  'c_int_arr',
  'c_number',
  'c_number_bare',
  'c_varchar2',
  'c_nvarchar2',
  'c_clob',
  'c_blob',
  'c_raw',
];

function isRealGaussDbAvailable(): Promise<boolean> {
  if (MAINTENANCE_URL.length === 0) return Promise.resolve(false);
  return createGaussDbDriver(MAINTENANCE_URL)
    .then(async (driver) => {
      await driver.query('select 1');
      await driver.close();
      return true;
    })
    .catch(() => false);
}

describe.runIf(await isRealGaussDbAvailable())(
  'gaussdb infer journeys — introspect → inferPslContract on a real server',
  () => {
    const driverRef: { current: Awaited<ReturnType<typeof createGaussDbDriver>> | null } = {
      current: null,
    };

    async function testDriver() {
      driverRef.current ??= await createGaussDbDriver(inferTestDatabaseUrl());
      return driverRef.current;
    }

    async function recreateTestDatabase() {
      // The test driver holds the only connection to the throwaway database —
      // close it first or the DROP fails with the database in use.
      if (driverRef.current) {
        await driverRef.current.close();
        driverRef.current = null;
      }
      const maintenance = await createGaussDbDriver(MAINTENANCE_URL);
      await maintenance.query(`DROP DATABASE IF EXISTS ${INFER_TEST_DB}`);
      await maintenance.query(`CREATE DATABASE ${INFER_TEST_DB}`);
      await maintenance.close();
    }

    beforeAll(async () => {
      await recreateTestDatabase();
    }, timeouts.spinUpPpgDev);

    afterAll(async () => {
      if (driverRef.current) {
        await driverRef.current.close();
        driverRef.current = null;
      }
      const maintenance = await createGaussDbDriver(MAINTENANCE_URL);
      await maintenance.query(`DROP DATABASE IF EXISTS ${INFER_TEST_DB}`);
      await maintenance.close();
    }, timeouts.spinUpPpgDev);

    it(
      'infers every column of the all-column table with the right type and modifiers',
      async () => {
        const driver = await testDriver();
        await driver.query(`CREATE TYPE ${ENUM_TYPE} AS ENUM ('new', 'done')`);
        await driver.query(ALL_COLUMN_DDL);

        const schemaIR = await familyInstance.introspect({ driver });
        const ast = familyInstance.inferPslContract(schemaIR);
        const inferredPsl = printPsl(ast, {
          pslBlockDescriptors: probeStack.authoringContributions.pslBlockDescriptors,
        });

        // Every column maps back onto its physical name.
        for (const physical of PHYSICAL_COLUMN_NAMES) {
          expect(inferredPsl).toContain(`@map("${physical}")`);
        }

        // Scalar set: type names with their lengths/precisions, nullability.
        // c_int is pinned line-scoped: bare 'Int?' would also match inside
        // 'BigInt?'/'SmallInt?' and lose discrimination between the three
        // int columns. The inferred field is renamed with @map("c_int").
        const cIntLine = inferredPsl.split('\n').find((line) => line.includes('@map("c_int")'));
        expect(cIntLine).toBeDefined();
        expect(cIntLine?.trimStart()).toContain('Int?');
        expect(cIntLine).not.toContain('BigInt');
        expect(cIntLine).not.toContain('SmallInt');
        expect(inferredPsl).toContain('BigInt?');
        expect(inferredPsl).toContain('SmallInt?');
        expect(inferredPsl).toContain('Float?');
        expect(inferredPsl).toContain('Real?');
        expect(inferredPsl).toContain('Boolean?');
        expect(inferredPsl).toContain('String?');
        expect(inferredPsl).toContain('VarChar(50)?');
        expect(inferredPsl).toContain('Char(10)?');
        expect(inferredPsl).toContain('Numeric(12, 2)?');
        expect(inferredPsl).toContain('Jsonb?');
        expect(inferredPsl).toContain('Json?');
        expect(inferredPsl).toContain('Bytes?');
        expect(inferredPsl).toContain('Uuid?');
        expect(inferredPsl).toContain('Timestamptz?');
        expect(inferredPsl).toContain('Timestamp?');
        expect(inferredPsl).toContain('Time?');
        expect(inferredPsl).toContain('Timetz?');
        expect(inferredPsl).toContain('Inet?');

        // Defaults across every shape the table carries.
        expect(inferredPsl).toContain('@default(42)');
        expect(inferredPsl).toContain('@default(7)');
        expect(inferredPsl).toContain('@default(1.5)');
        expect(inferredPsl).toContain('@default(true)');
        expect(inferredPsl).toContain('@default("hello")');
        expect(inferredPsl).toContain('@default(dbgenerated("\'{}\'::jsonb"))');
        expect(inferredPsl).toContain('@default(now())');
        expect(inferredPsl).toContain('@default("new")');
        expect(inferredPsl).toContain('@default([])');

        // A-mode identity lands as numeric with an autoincrement default.
        expect(inferredPsl).toContain('@id(map: "gj_infer_probe_pkey")');
        expect(inferredPsl).toContain('@default(autoincrement())');

        // Enum column: native_enum adoption + pg.enum constructor.
        expect(inferredPsl).toContain('pg.enum(GjInferStatus)?');
        expect(inferredPsl).toContain('native_enum GjInferStatus');
        expect(inferredPsl).toContain('@@map("gj_infer_status")');

        // Array columns: element type + list marker.
        expect(inferredPsl).toContain('String[]');
        expect(inferredPsl).toContain('Int[]');

        // Oracle-compat types. number/varchar2 ride their catalog aliases
        // (documented DDL-name boundary); the private-OID types carry their
        // own PSL names.
        expect(inferredPsl).toContain('Numeric(10, 2)?');
        expect(inferredPsl).toContain('Numeric?');
        expect(inferredPsl).toContain('VarChar(30)?');
        expect(inferredPsl).toContain('NVarChar2(30)?');
        expect(inferredPsl).toContain('Clob?');
        expect(inferredPsl).toContain('Blob?');
        expect(inferredPsl).toContain('Raw?');

        // The steered-out type stays Unsupported when it does appear.
        await driver.query(`ALTER TABLE ${TABLE} ADD COLUMN c_date date`);
        const withDate = familyInstance.inferPslContract(
          await familyInstance.introspect({ driver }),
        );
        const dateField = withDate.namespaces
          .find((ns) => ns.name === 'public')
          ?.models.find((m) => m.name === 'GjInferProbe')
          ?.fields.find((f) => f.name === 'cDate');
        expect(dateField?.typeName).toBe('Unsupported("datea")');
      },
      timeouts.spinUpPpgDev,
    );

    it(
      'round-trips an inferred contract through plan/apply on a fresh database and verifies clean',
      async () => {
        // A round-trip-executable subset of the all-column table. Three
        // shapes are excluded because AUTHORED contracts fail their DDL
        // rendering/verification the same way (pre-existing migration-layer
        // gaps, logged in verification-results.md section ten):
        //   - a numeric autoincrement identity (no executable DDL form),
        //   - an int8 literal default (renders `7::bigint`, which verify's
        //     default parser grades as a function expression),
        //   - a numeric literal default (decodeJson requires decimal text).
        await recreateTestDatabase();
        const driver = await testDriver();
        await driver.query(`CREATE TYPE ${ENUM_TYPE} AS ENUM ('new', 'done')`);
        await driver.query(`CREATE TABLE gj_infer_rt (
          id            int4 PRIMARY KEY,
          c_text        text DEFAULT 'hello',
          c_varchar     varchar(50),
          c_numeric     numeric(12,2),
          c_jsonb       jsonb DEFAULT '{}',
          c_timestamptz timestamptz DEFAULT now(),
          c_bool        boolean DEFAULT true,
          c_bigint      int8,
          c_enum        ${ENUM_TYPE} DEFAULT 'new',
          c_text_arr    text[] DEFAULT '{}',
          c_int_arr     int4[],
          c_number      number(10,2),
          c_varchar2    varchar2(30),
          c_nvarchar2   nvarchar2(30),
          c_clob        clob,
          c_blob        blob,
          c_raw         raw(32)
        )`);

        const schemaIR = await familyInstance.introspect({ driver });
        const ast = familyInstance.inferPslContract(schemaIR);
        const rtPsl = printPsl(ast, {
          pslBlockDescriptors: probeStack.authoringContributions.pslBlockDescriptors,
        });
        expect(rtPsl).toContain('model GjInferRt');
        expect(rtPsl).toContain('NVarChar2(30)?');
        expect(rtPsl).toContain('Clob?');
        expect(rtPsl).toContain('Blob?');
        expect(rtPsl).toContain('Raw?');

        const contract = buildContractFromPsl(rtPsl);

        // Fresh, empty database again: the inferred contract is executable
        // from nothing.
        await recreateTestDatabase();
        const freshDriver = await testDriver();

        const plan = await planContract(contract, emptySchema);
        await applyPlan(freshDriver, plan, contract);

        const introspected = await familyInstance.introspect({ driver: freshDriver });
        const verify = familyInstance.verifySchema({
          contract,
          schema: introspected,
          strict: true,
          frameworkComponents,
        });
        expect(verify.ok).toBe(true);
      },
      timeouts.spinUpPpgDev,
    );
  },
);
